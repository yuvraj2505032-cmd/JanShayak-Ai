export function getIndianLanguageConfig(localeOrCode: string | undefined | null): IndianLanguageConfig {
  const raw = String(localeOrCode || 'en-IN').trim().toLowerCase();
  const prefix = raw.split(/[-_]/)[0];
  return (
    INDIAN_22_LANGUAGES.find((l) => l.code.toLowerCase() === raw) ||
    INDIAN_22_LANGUAGES.find((l) => l.prefix.toLowerCase() === prefix) ||
    INDIAN_22_LANGUAGES[2] // default English (India)
  );
}

export function detectQueryTopicIn22Languages(query: string): {
  isFarmer: boolean;
  isStudent: boolean;
  isWomen: boolean;
  isPension: boolean;
  isHealth: boolean;
  isElectricity: boolean;
  isHousing: boolean;
  isLoan: boolean;
} {
  const q = query.toLowerCase();
  const hasAny = (category: keyof IndianLanguageConfig['keywords']) =>
    INDIAN_22_LANGUAGES.some((lang) => lang.keywords[category].some((kw) => q.includes(kw.toLowerCase())));

  return {
    isFarmer: /farmer|kisan|crop|agriculture/.test(q) || hasAny('farmer'),
    isStudent: /student|scholar|matric|college|school|education/.test(q) || hasAny('student'),
    isWomen: /women|woman|girl|ashirwad|shagun|marriage|widow|ujjwala|sukanya/.test(q) || hasAny('women'),
    isPension: /pension|old age|senior/.test(q) || hasAny('pension'),
    isHealth: /health|medical|hospital|sehat|ayushman|bima|treatment/.test(q) || hasAny('health'),
    isElectricity: /electricity|bijli|300|power/.test(q) || hasAny('electricity'),
    isHousing: /house|housing|awas|home/.test(q) || hasAny('housing'),
    isLoan: /loan|mudra|business|svanidhi|vishwakarma/.test(q) || hasAny('loan'),
  };
}
