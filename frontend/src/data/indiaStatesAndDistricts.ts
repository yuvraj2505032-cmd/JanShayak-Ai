export const ALL_INDIA_STATES_LIST: string[] = INDIA_STATES_AND_UTS.map((s) => s.name);

export function getStateMetadata(stateName: string): IndiaStateMetadata {
  const normalized = (stateName || 'Punjab').trim().toLowerCase();
  return (
    INDIA_STATES_AND_UTS.find(
      (s) =>
        s.name.toLowerCase() === normalized ||
        s.code.toLowerCase() === normalized ||
        normalized.includes(s.name.toLowerCase())
    ) || INDIA_STATES_AND_UTS[0]
  );
}

export function getDistrictsForState(stateName: string): DistrictInfo[] {
  const stateMeta = getStateMetadata(stateName);
  if (stateMeta.name === 'Punjab') {
    return PUNJAB_DISTRICTS;
  }

  return stateMeta.districts.map((distName, idx) => {
    const cleanName = distName.trim();
    const kendraCount = 18 + ((cleanName.length * 7 + idx * 5) % 38);
    const stdCode = 110 + ((idx * 13 + stateMeta.code.charCodeAt(0)) % 790);
    return {
      name: cleanName,
      namePa: `${cleanName} (${stateMeta.namePa})`,
      nameHi: `${cleanName} (${stateMeta.nameHi})`,
      headquarters: cleanName,
      sewaKendraCount: kendraCount,
      mainSewaKendraAddress: `District Collectorate / Mini Secretariat, ${stateMeta.sewaPortalName.split('(')[0].trim()}, ${cleanName}, ${stateMeta.name}`,
      dcOfficeContact: `0${stdCode}-224100`,
      helpline: stateMeta.helpline,
      popularSchemes: [
        `state-${stateMeta.code.toLowerCase()}-flagship`,
        'pm-kisan',
        'sarbat-sehat-bima',
        'pm-vishwakarma',
      ],
    };
  });
}

