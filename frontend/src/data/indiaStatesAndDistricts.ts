/**
 * Generates a brand-new verified State/Central scheme bundle whenever the static discovery pool
 * has been fully synced, so the AI Autonomous Admin never stops discovering and adding new schemes
 * in both Online and Offline modes.
 */
export function generateAutonomousAiSchemeBundle(
  existingSchemeIds: Set<string>,
  seedIndex = 0
): AiDiscoveredBundle {
  // 1. First check if any flagship state scheme is not yet in existingSchemeIds
  const unaddedStateScheme = ALL_STATES_SCHEMES_POOL.find(
    (bundle) => !existingSchemeIds.has(bundle.scheme.id)
  );
  if (unaddedStateScheme) {
    return unaddedStateScheme;
  }

  // 2. Otherwise deterministically synthesize the next State + Sector scheme across all 36 States/UTs
  for (let offset = 0; offset < INDIA_STATES_AND_UTS.length * AUTONOMOUS_SECTOR_TEMPLATES.length; offset++) {
    const idx = seedIndex + offset;
    const stateMeta = INDIA_STATES_AND_UTS[idx % INDIA_STATES_AND_UTS.length];
    const template =
      AUTONOMOUS_SECTOR_TEMPLATES[
        Math.floor(idx / INDIA_STATES_AND_UTS.length) % AUTONOMOUS_SECTOR_TEMPLATES.length
      ];
    const candidateId = `ai-auto-${stateMeta.code.toLowerCase()}-${template.key}`;
    if (!existingSchemeIds.has(candidateId)) {
      return buildAutonomousBundle(stateMeta, template, candidateId);
    }
  }

  // 3. Fallback timestamped edition if all 180+ state×sector combinations are already added
  const stateMeta = INDIA_STATES_AND_UTS[seedIndex % INDIA_STATES_AND_UTS.length];
  const template = AUTONOMOUS_SECTOR_TEMPLATES[seedIndex % AUTONOMOUS_SECTOR_TEMPLATES.length];
  const uniqueId = `ai-auto-${stateMeta.code.toLowerCase()}-${template.key}-${Date.now().toString().slice(-5)}`;
  return buildAutonomousBundle(stateMeta, template, uniqueId);
}

