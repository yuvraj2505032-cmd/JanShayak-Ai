const YOUTUBE_VIDEO_ID_PATTERN = /^[\w-]{11}$/;

function hashSchemeId(str: string): number {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) >>> 0;
  }
  return h;
}

export const getSchemeVideoIds = (
  schemeId: string,
  customPrimaryVideoId?: string
): string[] => {
  const result: string[] = [];

  if (customPrimaryVideoId && YOUTUBE_VIDEO_ID_PATTERN.test(customPrimaryVideoId)) {
    result.push(customPrimaryVideoId);
  }

  const curatedVideoIds = SCHEME_VIDEO_IDS[schemeId];
  if (curatedVideoIds?.length) {
    for (const id of curatedVideoIds) {
      if (YOUTUBE_VIDEO_ID_PATTERN.test(id) && !result.includes(id)) {
        result.push(id);
      }
    }
  }

  if (result.length < 3) {
    const startIdx = hashSchemeId(schemeId || 'default') % FALLBACK_SCHEME_VIDEO_IDS.length;
    for (let i = 0; i < FALLBACK_SCHEME_VIDEO_IDS.length && result.length < 3; i++) {
      const candidate = FALLBACK_SCHEME_VIDEO_IDS[(startIdx + i) % FALLBACK_SCHEME_VIDEO_IDS.length];
      if (!result.includes(candidate)) {
        result.push(candidate);
      }
    }
  }

  return result.slice(0, 3);
};

export interface SchemeYoutubeBundle {
  videoIds: string[];
  primaryVideoId: string;
  videoTitle: string;
  watchOnYoutubeUrl: string;
  punjabiSearchUrl: string;
  hindiSearchUrl: string;
}

export function getSchemeYoutubeBundle(scheme: {
  id: string;
  titleEn: string;
  youtubeVideoId?: string;
  youtubeVideoTitle?: string;
}): SchemeYoutubeBundle {
  const curatedIds = SCHEME_VIDEO_IDS[scheme.id];
  // Prefer curated primary ID if scheme.youtubeVideoId is not in curatedIds and schemeId is a known static scheme,
  // OR use scheme.youtubeVideoId if it is a newly AI-generated scheme not in SCHEME_VIDEO_IDS.
  const customPrimary = !curatedIds && scheme.youtubeVideoId ? scheme.youtubeVideoId : undefined;
  const videoIds = getSchemeVideoIds(scheme.id, customPrimary);
  const primaryVideoId = videoIds[0];

  return {
    videoIds,
    primaryVideoId,
    videoTitle:
      scheme.youtubeVideoTitle ||
      `${scheme.titleEn} — Complete Online Registration & Eligibility Video Guide`,
    watchOnYoutubeUrl: `https://www.youtube.com/watch?v=${primaryVideoId}`,
    punjabiSearchUrl: `https://www.youtube.com/results?search_query=${encodeURIComponent(
      `${scheme.titleEn} apply online Punjabi Punjab`
    )}`,
    hindiSearchUrl: `https://www.youtube.com/results?search_query=${encodeURIComponent(
      `${scheme.titleEn} apply online Hindi kaise kare`
    )}`,
  };
}
